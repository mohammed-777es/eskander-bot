# =========================================================
# ARABIC TEXT
# =========================================================

def shape_arabic(text):
    try:
        reshaped = arabic_reshaper.reshape(text)
        return get_display(reshaped)
    except Exception:
        return text


# =========================================================
# CREATE PDF
# =========================================================

def create_text_pdf(title, text, filename):
    path = os.path.join(tempfile.gettempdir(), filename)

    doc = SimpleDocTemplate(
        path,
        pagesize=A4,
        rightMargin=18 * mm,
        leftMargin=18 * mm,
        topMargin=18 * mm,
        bottomMargin=20 * mm,
    )

    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        "TitleEskander",
        parent=styles["Title"],
        fontName=PDF_FONT,
        fontSize=18,
        leading=24,
        alignment=TA_RIGHT,
        spaceAfter=14,
    )

    body_style = ParagraphStyle(
        "BodyEskander",
        parent=styles["BodyText"],
        fontName=PDF_FONT,
        fontSize=11,
        leading=18,
        alignment=TA_RIGHT,
        spaceAfter=8,
    )

    footer_style = ParagraphStyle(
        "FooterEskander",
        parent=styles["BodyText"],
        fontName=PDF_FONT,
        fontSize=8,
        leading=12,
        alignment=TA_LEFT,
        textColor=None,
    )

    story = []

    title_text = shape_arabic(title)

    story.append(
        Paragraph(title_text, title_style)
    )

    clean_text = text.replace("\r\n", "\n").replace("\r", "\n")

    paragraphs = clean_text.split("\n")

    for paragraph in paragraphs:
        paragraph = paragraph.strip()

        if not paragraph:
            story.append(Spacer(1, 5))
            continue

        safe_text = (
            paragraph
            .replace("&", "&amp;")
            .replace("<", "&lt;")
            .replace(">", "&gt;")
        )

        safe_text = shape_arabic(safe_text)

        story.append(
            Paragraph(safe_text, body_style)
        )

    story.append(Spacer(1, 15))

    footer = shape_arabic(BRAND_FOOTER)

    story.append(
        Paragraph(footer, footer_style)
    )

    doc.build(story)

    return path


