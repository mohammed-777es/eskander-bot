# =========================================================
# PDF HANDLER
# =========================================================

async def pdf_handler(update: Update, context: ContextTypes.DEFAULT_TYPE):

    document = update.message.document

    if not document:
        return

    filename = document.file_name or ""

    if not filename.lower().endswith(".pdf"):

        await update.message.reply_text(
            "❌ أرسل ملف PDF فقط."
        )

        return

    await update.message.reply_text(
        "📥 جاري قراءة ملف المحاضرة..."
    )

    try:

        file = await document.get_file()

        temp_path = os.path.join(
            tempfile.gettempdir(),
            f"lecture_{update.effective_user.id}.pdf"
        )

        await file.download_to_drive(temp_path)

        pdf = fitz.open(temp_path)

        extracted_text = []

        for page in pdf:

            text = page.get_text()

            if text:
                extracted_text.append(text)

        pdf.close()

        full_text = "\n".join(extracted_text).strip()

        if not full_text:

            await update.message.reply_text(
                "❌ لم أستطع استخراج نص من هذا الملف.\n\n"
                "تأكد أن ملف PDF يحتوي على نص قابل للقراءة."
            )

            return

        context.user_data["pdf_text"] = full_text

        context.user_data["pdf_filename"] = filename

        keyboard = [
            [
                InlineKeyboardButton(
                    "📝 ملخص عربي PDF",
                    callback_data="summary_ar"
                )
            ],
            [
                InlineKeyboardButton(
                    "🇬🇧 English Summary PDF",
                    callback_data="summary_en"
                )
            ],
            [
                InlineKeyboardButton(
                    "🌍 ترجمة PDF",
                    callback_data="translate"
                )
            ],
            [
                InlineKeyboardButton(
                    "🧠 اختبار تفاعلي",
                    callback_data="quiz"
                )
            ],
        ]

        reply_markup = InlineKeyboardMarkup(keyboard)

        await update.message.reply_text(
            "✅ تم استلام المحاضرة وقراءة محتواها بنجاح.\n\n"
            "📚 اختر الخدمة التي تريدها:",
            reply_markup=reply_markup
        )

        try:
            os.remove(temp_path)
        except Exception:
            pass

    except Exception as e:

        print(
            f"PDF ERROR: {type(e).__name__}: {e}"
        )

        await update.message.reply_text(
            "❌ حدث خطأ أثناء قراءة ملف PDF.\n\n"
            "راجع Render Logs لمعرفة السبب."
        )


