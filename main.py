# =========================
# CREATE PDF
# =========================

def shape_arabic(text):
    reshaped = arabic_reshaper.reshape(text)
    return get_display(reshaped)


def create_text_pdf(text, title, output_path):
    if not FONT_PATH:
        raise FileNotFoundError(
            "Arabic PDF font was not found."
        )

    document = SimpleDocTemplate(
        output_path,
        pagesize=A4,
        rightMargin=45,
        leftMargin=45,
        topMargin=45,
        bottomMargin=45
    )

    title_style = ParagraphStyle(
        "TitleStyle",
        fontName="DejaVuSans",
        fontSize=16,
        leading=25,
        alignment=TA_RIGHT,
        spaceAfter=20
    )

    text_style = ParagraphStyle(
        "TextStyle",
        fontName="DejaVuSans",
        fontSize=11,
        leading=20,
        alignment=TA_RIGHT,
        spaceAfter=8
    )

    footer_style = ParagraphStyle(
        "FooterStyle",
        fontName="DejaVuSans",
        fontSize=9,
        leading=16,
        alignment=TA_RIGHT,
        spaceBefore=20
    )

    story = []

    title_display = shape_arabic(title)

    story.append(
        Paragraph(
            html.escape(title_display),
            title_style
        )
    )

    for line in text.splitlines():

        line = line.strip()

        if not line:
            story.append(
                Spacer(1, 8)
            )
            continue

        line_display = shape_arabic(line)

        safe_line = html.escape(
            line_display
        )

        story.append(
            Paragraph(
                safe_line,
                text_style
            )
        )

    story.append(
        Spacer(1, 20)
    )

    footer_text = (
        "─── ✦ ───<br/>"
        "✦ Generated by: Mohammed Eskander<br/>"
        "Mohammed Eskander ALzabidee"
    )

    footer_display = shape_arabic(
        footer_text.replace("<br/>", "\n")
    )

    footer_display = (
        footer_display
        .replace("\n", "<br/>")
    )

    story.append(
        Paragraph(
            footer_display,
            footer_style
        )
    )

    document.build(story)


