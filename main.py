async def pdf_handler(
    update: Update,
    context: ContextTypes.DEFAULT_TYPE
):

    document = update.message.document

    if not document:
        return

    filename = document.file_name or ""

    if not filename.lower().endswith(".pdf"):

        await update.message.reply_text(
            "❌ أرسل ملف PDF فقط."
        )

        return

    processing = await update.message.reply_text(
        "📥 جاري قراءة ملف PDF..."
    )

    pdf_path = None

    try:

        file = await document.get_file()

        temp_dir = tempfile.gettempdir()

        pdf_path = os.path.join(
            temp_dir,
            f"{document.file_unique_id}.pdf"
        )

        await file.download_to_drive(pdf_path)

        doc = fitz.open(pdf_path)

        text = ""

        for page in doc:

            text += page.get_text()

            text += "\n"

        doc.close()

        if pdf_path and os.path.exists(pdf_path):

            os.remove(pdf_path)

            pdf_path = None

        if not text.strip():

            await processing.delete()

            await update.message.reply_text(
                "❌ لم أتمكن من استخراج النص من هذا الملف."
            )

            return

        context.user_data["pdf_text"] = text

        await processing.delete()

        keyboard = [
            [
                InlineKeyboardButton(
                    "📚 تلخيص بالعربي",
                    callback_data="summary_ar"
                )
            ],
            [
                InlineKeyboardButton(
                    "🇬🇧 تلخيص بالإنجليزي",
                    callback_data="summary_en"
                )
            ],
            [
                InlineKeyboardButton(
                    "🌍 ترجمة",
                    callback_data="translate"
                )
            ],
            [
                InlineKeyboardButton(
                    "📝 اختبار تفاعلي",
                    callback_data="quiz"
                )
            ]
        ]

        await update.message.reply_text(
            "✅ تم استلام المحاضرة بنجاح.\n\n"
            "اختر الخدمة التي تريدها:",
            reply_markup=InlineKeyboardMarkup(
                keyboard
            )
        )

    except Exception as e:

        print(
            f"PDF ERROR: "
            f"{type(e).__name__}: {e}"
        )

        if pdf_path and os.path.exists(pdf_path):

            try:
                os.remove(pdf_path)
            except Exception:
                pass

        try:

            await processing.delete()

        except Exception:

            pass

        await update.message.reply_text(
            "❌ حدث خطأ أثناء قراءة ملف PDF."
        )


