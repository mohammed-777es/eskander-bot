# =========================
# MAIN
# =========================

def main():

    print(
        "⚡ Starting Eskander AI Studio..."
    )


    threading.Thread(
        target=start_health_server,
        daemon=True
    ).start()


    app = (
        ApplicationBuilder()
        .token(BOT_TOKEN)
        .build()
    )


    app.add_handler(
        CommandHandler(
            "start",
            start
        )
    )


    app.add_handler(
        CallbackQueryHandler(
            button_handler
        )
    )


    app.add_handler(
        MessageHandler(
            filters.Document.PDF,
            handle_document
        )
    )


    app.add_error_handler(
        error_handler
    )


    print(
        "✅ Bot is running..."
    )


    app.run_polling()


# =========================
# RUN
# =========================

if __name__ == "__main__":

    main()
