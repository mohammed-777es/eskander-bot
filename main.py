def create_text_pdf(title, content):

    fd, pdf_path = tempfile.mkstemp(
        suffix=".pdf",
        prefix="eskander_"
    )

    os.close(fd)

    font_name = "DejaVu" if FONT_PATH else "Helvetica"

    doc = SimpleDocTemplate(
        pdf_path,
        pagesize=A4,
        rightMargin=18 * mm,
        leftMargin=18 * mm,
        topMargin=18 * mm,
        bottomMargin=22 * mm,
    )

    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        "ArabicTitle",
        parent=styles["Title"],
        fontName=font_name,
        fontSize=18,
        leading=24,
        alignment=TA_CENTER,
        spaceAfter=14,
    )

    body_style = ParagraphStyle(
        "ArabicBody",
        parent=styles["BodyText"],
        fontName=font_name,
        fontSize=11,
        leading=18,
        alignment=TA_RIGHT,
        spaceAfter=8,
    )

    footer_style = ParagraphStyle(
        "Footer",
        parent=styles["BodyText"],
        fontName=font_name,
        fontSize=8,
        leading=12,
        alignment=TA_CENTER,
        spaceBefore=12,
    )

    story = []

    shaped_title = shape_arabic(title)

    story.append(
        Paragraph(
            shaped_title,
            title_style
        )
    )

    story.append(
        Spacer(1, 5 * mm)
    )

    lines = content.splitlines()

    for line in lines:

        line = line.strip()

        if not line:
            story.append(
                Spacer(1, 4)
            )
            continue

        line = (
            line.replace("&", "&amp;")
            .replace("<", "&lt;")
            .replace(">", "&gt;")
        )

        shaped_line = shape_arabic(line)

        story.append(
            Paragraph(
                shaped_line,
                body_style
            )
        )

    story.append(
        Spacer(1, 10 * mm)
    )

    footer_1 = shape_arabic("─── ✦ ───")
    footer_2 = "✦ Generated by: Mohammed Eskander"
    footer_3 = (
        "𝙼𝚘𝚑𝚊𝚖𝚖𝚎𝚍 𝙴𝚜𝚔𝚊𝚗𝚍𝚎𝚛 "
        "𝙰𝙻𝚣𝚊𝚋𝚒𝚍𝚎'𝚎"
    )

    story.append(
        Paragraph(
            f"{footer_1}<br/>"
            f"{footer_2}<br/>"
            f"{footer_3}",
            footer_style
        )
    )

    doc.build(story)

    return pdf_path


